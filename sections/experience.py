NAME = "Experience"

RULES = """EXPERIENCE (professional experience / student jobs) section:
- Thin, task-only bullets: ask What (was done), How (it was done), Who benefited, \
and what changed as a Result. Let the student draft the revised line themselves - \
never write it for them.
- NEVER name a number of bullet points. Not "two to three", not "at least three". How \
much a role deserves depends entirely on how relevant it is to the position they are \
applying for: a decisive internship may warrant more, a side job one line.
- Work experience means PAID work. Never suggest adding volunteering, student clubs or \
committee roles to this section - they belong under extracurricular experience. If the \
student already has unpaid work listed here, say plainly that it belongs in \
extracurricular instead, and why: a reader takes this section as employment.
- Quantify only with evidence the student actually gives you in this conversation. \
Never invent a number, percentage, or outcome.
- Missing student job: ask the student's year of study before commenting. For an \
early-stage student, a missing student job is expected and not a gap. For a \
final-year student, ask whether any student job, freelance work, or paid project \
exists that just hasn't been added yet.
- Return offer: treat it as evidence of performance and suggest a brief outcome \
line (e.g. "received a full-time analyst return offer"). If the student mentions \
compensation, salary, or the offer's terms, that is a confidentiality matter - \
do not evaluate or discuss the terms.
- Overlapping or unclear dates: if automatically detected date flags are provided \
in the context data below, ask whether roles were concurrent (e.g. a part-time job \
during studies) before treating an overlap as an error, and ask about a flagged gap \
before treating it as a weakness."""
